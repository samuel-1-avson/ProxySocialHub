//! Host tool: generate ProxyHubb batch Groth16 VK + sample proof (BC-11-B).
//! Circuit: public Fr == private Fr (batch_digest field element).
use ark_bn254::{Bn254, Fr, G1Affine, G2Affine};
use ark_ff::{BigInteger, PrimeField};
use ark_groth16::{Groth16, Proof, ProvingKey, VerifyingKey};
use ark_relations::r1cs::{ConstraintSynthesizer, ConstraintSystemRef, SynthesisError};
use ark_serialize::{CanonicalSerialize, Compress};
use ark_snark::SNARK;
use ark_std::rand::rngs::StdRng;
use ark_std::rand::SeedableRng;
use sha2::{Digest, Sha256};
use std::fs;
use std::ops::Neg;
use std::path::PathBuf;

#[derive(Clone)]
struct BatchDigestCircuit {
    digest: Option<Fr>,
}

impl ConstraintSynthesizer<Fr> for BatchDigestCircuit {
    fn generate_constraints(self, cs: ConstraintSystemRef<Fr>) -> Result<(), SynthesisError> {
        use ark_relations::r1cs::{LinearCombination, Variable};
        let w = cs.new_witness_variable(|| self.digest.ok_or(SynthesisError::AssignmentMissing))?;
        let p = cs.new_input_variable(|| self.digest.ok_or(SynthesisError::AssignmentMissing))?;
        cs.enforce_constraint(
            LinearCombination::from(w),
            LinearCombination::from(Variable::One),
            LinearCombination::from(p),
        )?;
        Ok(())
    }
}

fn rev32(chunk: &[u8]) -> [u8; 32] {
    let mut out = [0u8; 32];
    for (i, b) in chunk.iter().take(32).enumerate() {
        out[31 - i] = *b;
    }
    out
}

/// G1 → 64-byte BE `x || y` (Ethereum / alt_bn128 / groth16-solana).
fn g1_uncompressed_be(p: &G1Affine) -> [u8; 64] {
    let mut le = Vec::new();
    p.serialize_with_mode(&mut le, Compress::No).unwrap();
    assert_eq!(le.len(), 64);
    let mut out = [0u8; 64];
    out[..32].copy_from_slice(&rev32(&le[..32]));
    out[32..].copy_from_slice(&rev32(&le[32..64]));
    out
}

/// G2 → 128-byte BE `x.c1 || x.c0 || y.c1 || y.c0`.
/// arkworks emits LE `x.c0 || x.c1 || y.c0 || y.c1`; alt_bn128 swaps Fp2 limbs.
fn g2_uncompressed_be(p: &G2Affine) -> [u8; 128] {
    let mut le = Vec::new();
    p.serialize_with_mode(&mut le, Compress::No).unwrap();
    assert_eq!(le.len(), 128);
    let mut out = [0u8; 128];
    out[..32].copy_from_slice(&rev32(&le[32..64])); // x.c1
    out[32..64].copy_from_slice(&rev32(&le[..32])); // x.c0
    out[64..96].copy_from_slice(&rev32(&le[96..128])); // y.c1
    out[96..].copy_from_slice(&rev32(&le[64..96])); // y.c0
    out
}

fn fr_to_be(f: &Fr) -> [u8; 32] {
    let le = f.into_bigint().to_bytes_le();
    let mut be = [0u8; 32];
    for (i, b) in le.iter().take(32).enumerate() {
        be[31 - i] = *b;
    }
    be
}

fn hash_batch_digest(
    root: [u8; 32],
    session_count: u32,
    total_bytes: u64,
    period_start: i64,
    period_end: i64,
    leaves_hash: [u8; 32],
) -> Fr {
    let mut h = Sha256::new();
    h.update(root);
    h.update(session_count.to_le_bytes());
    h.update(total_bytes.to_le_bytes());
    h.update(period_start.to_le_bytes());
    h.update(period_end.to_le_bytes());
    h.update(leaves_hash);
    Fr::from_le_bytes_mod_order(&h.finalize())
}

fn fmt_arr(name: &str, bytes: &[u8]) -> String {
    let nums: Vec<String> = bytes.iter().map(|b| b.to_string()).collect();
    format!(
        "pub const {}: [u8; {}] = [\n    {}\n];\n",
        name,
        bytes.len(),
        nums.join(", ")
    )
}

fn main() {
    let mut rng = StdRng::seed_from_u64(0x5052_4F58_5948_5542);
    let (pk, vk): (ProvingKey<Bn254>, VerifyingKey<Bn254>) =
        Groth16::<Bn254>::circuit_specific_setup(BatchDigestCircuit { digest: None }, &mut rng)
            .expect("setup");

    let root = [0x11u8; 32];
    let leaves_hash = [0x22u8; 32];
    let digest = hash_batch_digest(root, 3, 1000, 1, 2, leaves_hash);
    let proof: Proof<Bn254> = Groth16::<Bn254>::prove(
        &pk,
        BatchDigestCircuit {
            digest: Some(digest),
        },
        &mut rng,
    )
    .expect("prove");

    let proof_a = g1_uncompressed_be(&proof.a.neg());
    let proof_b = g2_uncompressed_be(&proof.b);
    let proof_c = g1_uncompressed_be(&proof.c);

    let alpha = g1_uncompressed_be(&vk.alpha_g1);
    let beta = g2_uncompressed_be(&vk.beta_g2);
    let gamma = g2_uncompressed_be(&vk.gamma_g2);
    let delta = g2_uncompressed_be(&vk.delta_g2);
    let ic: Vec<[u8; 64]> = vk.gamma_abc_g1.iter().map(g1_uncompressed_be).collect();
    assert_eq!(ic.len(), 2);

    let mut vk_hash_input = Vec::new();
    for part in [&alpha[..], &beta[..], &gamma[..], &delta[..], &ic[0][..], &ic[1][..]] {
        vk_hash_input.extend_from_slice(part);
    }
    let vk_hash = Sha256::digest(&vk_hash_input);
    let pub_be = fr_to_be(&digest);

    let mut out = String::new();
    out.push_str("// @generated by tools/gen-batch-vk — do not edit by hand\n");
    out.push_str("// BC-11-B / Wave 5.A batch digest-v2 Groth16 verifying key (1 public input).\n");
    out.push_str("#![allow(dead_code, clippy::all)]\n\n");
    out.push_str(&fmt_arr("VK_ALPHA_G1", &alpha));
    out.push_str(&fmt_arr("VK_BETA_G2", &beta));
    out.push_str(&fmt_arr("VK_GAMMA_G2", &gamma));
    out.push_str(&fmt_arr("VK_DELTA_G2", &delta));
    out.push_str(&fmt_arr("VK_IC0", &ic[0]));
    out.push_str(&fmt_arr("VK_IC1", &ic[1]));
    out.push_str(&fmt_arr("VK_HASH", vk_hash.as_slice()));
    out.push_str("\n// Sample proof for host/unit tests.\n");
    out.push_str(&fmt_arr("SAMPLE_PROOF_A", &proof_a));
    out.push_str(&fmt_arr("SAMPLE_PROOF_B", &proof_b));
    out.push_str(&fmt_arr("SAMPLE_PROOF_C", &proof_c));
    out.push_str(&fmt_arr("SAMPLE_PUBLIC_INPUT", &pub_be));
    out.push_str(&fmt_arr("SAMPLE_BATCH_ROOT", &root));
    out.push_str(&fmt_arr("SAMPLE_LEAVES_HASH", &leaves_hash));

    let dest = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../programs/proxyhub/src/groth16_vk_generated.rs");
    fs::create_dir_all(dest.parent().unwrap()).ok();
    fs::write(&dest, &out).expect("write vk");
    println!("wrote {}", dest.display());
    println!("vk_hash={}", hex::encode(vk_hash));

    // Host-side alt_bn128 check: encoding must verify with groth16-solana.
    {
        use groth16_solana::groth16::{Groth16Verifier, Groth16Verifyingkey};
        let ic = [ic[0], ic[1]];
        let vk = Groth16Verifyingkey {
            nr_pubinputs: 1,
            vk_alpha_g1: alpha,
            vk_beta_g2: beta,
            vk_gamme_g2: gamma,
            vk_delta_g2: delta,
            vk_ic: &ic[..],
        };
        let public_inputs = [pub_be];
        let mut verifier = Groth16Verifier::new(
            &proof_a,
            &proof_b,
            &proof_c,
            &public_inputs,
            &vk,
        )
        .expect("groth16 verifier new");
        verifier.verify().expect("host groth16-solana verify failed — fix endianness");
        println!("host verify: OK");
    }
}
