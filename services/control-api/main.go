// @title           ProxySocialHub Control API
// @version         1.0
// @description     This is the control plane API for ProxySocialHub.
// @termsOfService  http://swagger.io/terms/

// @contact.name   API Support
// @contact.url    http://www.swagger.io/support
// @contact.email  support@swagger.io

// @license.name  Apache 2.0
// @license.url   http://www.apache.org/licenses/LICENSE-2.0.html

// @host      localhost:8080
// @BasePath  /v1

// @securityDefinitions.apikey ApiKeyAuth
// @in header
// @name Authorization
func main() {
	// Load .env file
	if err := godotenv.Load(); err != nil {
		// We don't log fatal here because we might be in prod with real env vars
		fmt.Println("No .env file found")
	}

	// Initialize structured logging first
	logging.Init()

	// Load Configuration
	cfg, err := config.Load()
	if err != nil {
		logging.Logger.Fatal().Err(err).Msg("Failed to load configuration")
	}

	// Initialize Database
	if err := db.Init(cfg.Database.DatabaseURL); err != nil {
		logging.Error(err).Msg("Failed to connect to database - specific features will be unavailable")
	}

	// Initialize Internal Redis (used by API handlers)
	if err := internalRedis.Init(); err != nil {
		logging.Warn().Err(err).Msg("Internal Redis initialization failed")
	}

	// Initialize Redis cache
	if err := cache.Connect(cfg.Database.RedisURL); err != nil {
		logging.Warn().Err(err).Msg("Redis connection failed")
	}
	defer cache.Close()

	// Initialize Event Queue (Redis-backed)
	if cache.Client != nil {
		queue := events.NewRedisQueue(cache.Client)
		api.InitEventQueue(queue)
		logging.Info().Msg("Event Queue initialized")

		// Start Background Worker
		go worker.StartConsumers(queue)
	} else {
		logging.Warn().Msg("Redis client not available for Event Queue")
	}

	// Initialize Oracle Signer
	if cfg.Crypto.OraclePrivateKey != "" {
		signer, err := crypto.NewSigner(cfg.Crypto.OraclePrivateKey)
		if err != nil {
			logging.Error(err).Msg("Failed to initialize Oracle Signer")
		} else {
			api.InitOracleSigner(signer)
			logging.Info().Msg("Oracle Signer initialized")
		}
	} else {
		logging.Warn().Msg("ORACLE_PRIVATE_KEY not set - usage signing disabled")
	}

	// Initialize Event Indexer (Blockchain)
	if cfg.Blockchain.RegistryAddress != "" {
		idx, err := indexer.NewIndexer(cfg)
		if err != nil {
			logging.Error(err).Msg("Failed to initialize Indexer")
		} else {
			// Start indexer in background
			go idx.Start(context.Background())
		}
	}

	// Initialize Email service
	emailConfig := email.Config{
		SMTPHost:  cfg.Email.SMTPHost,
		SMTPPort:  cfg.Email.SMTPPort,
		SMTPUser:  cfg.Email.SMTPUser,
		SMTPPass:  cfg.Email.SMTPPass,
		FromEmail: cfg.Email.FromEmail,
		FromName:  cfg.Email.FromName,
		AppURL:    cfg.Email.AppURL,
		Enabled:   cfg.Email.Enabled,
	}
	if err := email.Init(emailConfig); err != nil {
		logging.Warn().Err(err).Msg("Email service initialization failed")
	}

	r := gin.Default()

	// CORS Middleware with configurable origins
	r.Use(corsMiddleware(cfg.Server.CORSOrigins))

	// Request ID and structured logging
	r.Use(logging.RequestID())
	r.Use(logging.RequestLogger())

	// Compression
	r.Use(gzip.Gzip(gzip.DefaultCompression))

	// Security Middleware
	r.Use(api.SecureHeaders())
	r.Use(api.InputValidationMiddleware())
	r.Use(middleware.RateLimitByEndpoint()) // Redis-backed rate limiting
	r.Use(api.PrometheusMiddleware())

	// Health check (public)
	r.GET("/health", func(c *gin.Context) {
		c.JSON(http.StatusOK, gin.H{"status": "ok", "service": "control-api"})
	})

	// Metrics endpoint (public)
	api.RegisterMetricsEndpoint(r)

	// Swagger UI
	r.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))

	// Public routes (no auth required)
	_ = r.Group("/v1")
	{
		// No legacy auth routes needed
	}

	// Protected routes (auth required - JWT or API Key)
	protected := r.Group("/v1")
	protected.Use(middleware.SupabaseAuthMiddleware(cfg))
	{
		api.RegisterKycRoutes(protected)
		api.RegisterWalletRoutes(protected)
		api.RegisterSessionRoutes(protected)
		api.RegisterUsageRoutes(protected)
		api.RegisterCircleRoutes(protected)
		api.RegisterAnalyticsRoutes(protected)
		api.RegisterGeoRoutes(protected)
		api.RegisterAPIKeyRoutes(protected)    // API key management endpoints
		api.RegisterWebSocketRoutes(protected) // WebSocket endpoint

		// Social Hub features
		api.RegisterProfileRoutes(protected)   // Profiles and follows
		api.RegisterListingRoutes(protected)   // Marketplace listings
		api.RegisterOrderRoutes(protected)     // Orders/purchases
		api.RegisterReviewRoutes(protected)    // Reviews and ratings
		api.RegisterMessagingRoutes(protected) // Direct messaging
		api.RegisterFeedRoutes(protected)      // Feed and discovery
		api.RegisterFriendRoutes(protected)    // Friend System (NEW)

		// Phase 10: New Features
		api.RegisterEscrowRoutes(protected)       // Escrow payments
		api.RegisterSubscriptionRoutes(protected) // Subscription plans
		api.RegisterBadgeRoutes(protected)        // Achievement badges

		// Phase 11: Remaining Features
		api.RegisterReferralRoutes(protected)     // Referral program
		api.RegisterFavoriteRoutes(protected)     // Favorites/watchlist
		api.RegisterSellerTierRoutes(protected)   // Seller tiers
		api.RegisterSavedSearchRoutes(protected)  // Saved searches
		api.RegisterTeamRoutes(protected)         // Team accounts
		api.RegisterIPAllowlistRoutes(protected)  // IP allowlist
		api.RegisterGDPRRoutes(protected)         // GDPR data export
		api.RegisterProviderNodeRoutes(protected) // Multi-node management

		// Final Features
		api.RegisterSmartMatchingRoutes(protected) // AI proxy matching
		api.RegisterForumRoutes(protected)         // Community forum
		api.RegisterOnboardingRoutes(protected)    // Provider onboarding
	}

	// Admin routes
	admin := r.Group("/v1/admin")
	admin.Use(middleware.SupabaseAuthMiddleware(cfg), api.RequirePermission("admin:access"))
	{
		// KYC Management
		admin.GET("/kyc/pending", api.GetPendingKycVerifications)
		admin.POST("/kyc/:id/approve", api.AdminApproveKyc)
		admin.POST("/kyc/:id/reject", api.AdminRejectKyc)

		// User, Node, Payout, Stats Management
		api.RegisterAdminRoutes(admin)

		// Health Monitoring
		api.RegisterHealthRoutes(admin)

		// Provider Onboarding Management
		api.RegisterAdminOnboardingRoutes(admin)
	}

	// Start background health monitoring
	go func() {
		healthConfig := getHealthConfig()
		health.Start(healthConfig)

		// Start system dependency monitoring (check every 1 minute)
		health.StartSystemMonitor(1 * time.Minute)
	}()

	// Create HTTP server
	srv := &http.Server{
		Addr:    ":" + cfg.Server.Port,
		Handler: r,
	}

	// Start server in a goroutine
	go func() {
		logging.Info().Str("port", cfg.Server.Port).Msg("Starting control-api")
		if err := srv.ListenAndServe(); err != nil && err != http.ErrServerClosed {
			logging.Logger.Fatal().Err(err).Msg("listen failed")
		}
	}()

	// Wait for interrupt signal to gracefully shutdown the server with a timeout of 5 seconds
	quit := make(chan os.Signal, 1)
	// kill (no param) default send syscall.SIGTERM
	// kill -2 is syscall.SIGINT
	// kill -9 is syscall.SIGKILL but can't be caught, so don't need to add it
	signal.Notify(quit, syscall.SIGINT, syscall.SIGTERM)
	<-quit
	logging.Info().Msg("Shutting down server...")

	// The context is used to inform the server it has 5 seconds to finish
	// the request it is currently handling
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	if err := srv.Shutdown(ctx); err != nil {
		logging.Logger.Fatal().Err(err).Msg("Server forced to shutdown")
	}

	logging.Info().Msg("Server exiting")
}

func corsMiddleware(allowedOrigins []string) gin.HandlerFunc {
	return func(c *gin.Context) {
		origin := c.Request.Header.Get("Origin")

		// Check if origin is allowed
		allowed := false
		for _, o := range allowedOrigins {
			if strings.TrimSpace(o) == origin {
				allowed = true
				break
			}
		}

		if allowed {
			c.Writer.Header().Set("Access-Control-Allow-Origin", origin)
		}

		c.Writer.Header().Set("Access-Control-Allow-Credentials", "true")
		c.Writer.Header().Set("Access-Control-Allow-Headers", "Content-Type, Content-Length, Accept-Encoding, X-CSRF-Token, Authorization, accept, origin, Cache-Control, X-Requested-With, Proxy-Authorization")
		c.Writer.Header().Set("Access-Control-Allow-Methods", "POST, OPTIONS, GET, PUT, DELETE, PATCH")

		if c.Request.Method == "OPTIONS" {
			c.AbortWithStatus(204)
			return
		}

		c.Next()
	}
}

// getHealthConfig returns health monitoring configuration from environment or defaults
func getHealthConfig() health.Config {
	return health.DefaultConfig()
}
