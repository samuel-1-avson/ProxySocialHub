# Record P1 criterion bench numbers into docs/P1_BASELINE.md (append section with timestamp).
# Prereq: Rust toolchain. Full bench takes several minutes.
param(
    [switch]$Quick,
    [string]$OutFile = "docs/P1_BASELINE.md"
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root

Write-Host "== P1 baseline recording (Quick=$Quick) =="

$script:lines = @()
$script:lines += ""
$script:lines += "## Run $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss zzz')"
$script:lines += ""
$script:lines += "Machine: $env:COMPUTERNAME"
$script:lines += "Rust: $(rustc -V 2>$null)"
$script:lines += ""

function Invoke-BenchSection($name, $bench) {
    $prevEap = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try {
        if ($Quick) {
            Write-Host ">> cargo bench --bench $bench -- --test"
            $out = & cargo bench --bench $bench -- --test 2>&1 | Out-String
        } else {
            Write-Host ">> cargo bench --bench $bench"
            $out = & cargo bench --bench $bench 2>&1 | Out-String
        }
        if ($LASTEXITCODE -ne 0) {
            throw "cargo bench --bench $bench failed (exit $LASTEXITCODE)"
        }
    } finally {
        $ErrorActionPreference = $prevEap
    }
    $script:lines += "### $name"
    $script:lines += ""
    $script:lines += '```'
    $script:lines += ($out.TrimEnd())
    $script:lines += '```'
    $script:lines += ""
}

Invoke-BenchSection "registry_bench" "registry_bench"
Invoke-BenchSection "hotpath_bench" "hotpath_bench"

$header = @"
# P1 performance baseline

Auto-generated by ``scripts/p1-record-baseline.ps1``. Compare ``read_get_best`` vs ``rebuild_snapshot`` at 10k nodes.

**Sign-off rule:** snapshot read should be orders of magnitude faster than rebuild at the same N.

"@

if (-not (Test-Path $OutFile)) {
    Set-Content -Path $OutFile -Value $header -Encoding utf8
}
Add-Content -Path $OutFile -Value ($script:lines -join "`n") -Encoding utf8

Write-Host "Appended results to $OutFile"
Write-Host "HTML reports: target/criterion/*/report/index.html"
