# Bootstrap a signed provider-node for the main Docker Compose stack.
#
# Writes config/docker/provider.compose.env (gitignored).
#
# Usage:
#   .\scripts\bootstrap-provider-docker.ps1
#   .\scripts\bootstrap-provider-docker.ps1 -StartProvider
#   .\scripts\bootstrap-provider-docker.ps1 -ForceNewToken -StartProvider -Build

param(
    [string]$ApiBaseUrl = "http://localhost:18080",
    [string]$PostgresHostPort = "",
    [switch]$StartProvider,
    [switch]$ForceNewToken,
    [switch]$ResyncHotkey,
    [switch]$Build,
    [switch]$SkipAuthTest
)

$ErrorActionPreference = "Stop"
$repoRoot = Split-Path -Parent $PSScriptRoot
Set-Location $repoRoot

function Load-DotEnv([string]$path) {
    if (-not (Test-Path $path)) { return }
    Get-Content $path | ForEach-Object {
        if ($_ -match "^\s*([^#=]+)=(.*)$") {
            $k = $matches[1].Trim()
            $v = $matches[2].Trim().Trim('"').Trim("'")
            # Strip inline comments (e.g. GIN_MODE=debug # release) — Docker Compose does not strip these.
            if ($v -match '^([^#]+)') { $v = $matches[1].Trim() }
            Set-Item -Path "env:$k" -Value $v
        }
    }
}

function Read-ComposeEnv([string]$path) {
    $result = @{ ApiKey = ""; SigningKey = "" }
    if (-not (Test-Path $path)) { return $result }
    $content = Get-Content $path -Raw
    if ($content -match 'PROXYHUB_API_KEY=(\S+)') { $result.ApiKey = $matches[1].Trim() }
    if ($content -match 'PROXYHUB_PROVIDER_SIGNING_KEY=(\S+)') { $result.SigningKey = $matches[1].Trim() }
    return $result
}

function Write-ComposeEnv([string]$path, [string]$apiKey, [string]$signingKey) {
    $dir = Split-Path -Parent $path
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
    @"
# Generated by bootstrap-provider-docker.ps1 at $(Get-Date -Format o)
# Dev/local only — do not commit.

PROXYHUB_API_KEY=$apiKey
PROXYHUB_PROVIDER_SIGNING_KEY=$signingKey
"@ | Set-Content -Path $path -Encoding utf8
}

function Test-PostgresDockerAuth([string]$container, [string]$user, [string]$db, [string]$password) {
    if (-not $password) { return $false }
    $out = docker exec -e "PGPASSWORD=$password" $container `
        psql -U $user -d $db -tAc "SELECT 1" 2>&1
    return $LASTEXITCODE -eq 0
}

function Test-ProviderAuth([string]$baseUrl, [string]$apiKey) {
    if (-not $apiKey -or $apiKey.Length -lt 32) { return $false }
    try {
        $body = @{ token = $apiKey } | ConvertTo-Json
        $resp = Invoke-RestMethod -Uri ($baseUrl.TrimEnd('/') + "/v1/provider/auth") -Method Post -Body $body -ContentType "application/json" -TimeoutSec 10
        return [bool]$resp.valid
    }
    catch {
        return $false
    }
}

function Invoke-ProviderDevToken([string[]]$extraArgs, [string]$HostDatabaseUrl) {
    $jsonPath = Join-Path $env:TEMP ("proxyhubb-provider-dev-token-{0}.json" -f [Guid]::NewGuid().ToString("N"))
    $baseArgs = @(
        "run", "./cmd/provider_dev_token",
        "-env-file", (Join-Path $repoRoot ".env"),
        "-api-url", "http://control-api:8080",
        "-gateway", "edge-gateway:3128",
        "-output-json", $jsonPath
    )
    Push-Location (Join-Path $repoRoot "services\control-api")
    $prevDb = $env:DATABASE_URL
    $env:DATABASE_URL = $HostDatabaseUrl
    try {
        $prevEap = $ErrorActionPreference
        $ErrorActionPreference = "Continue"
        $stderr = & go @baseArgs @("-ensure-profile") @extraArgs 2>&1
        $exit = $LASTEXITCODE
        $ErrorActionPreference = $prevEap
        if ($exit -ne 0) {
            if ($stderr) { Write-Host ($stderr | Out-String) }
            throw "provider_dev_token failed (exit $exit)"
        }
        if ($stderr) {
            $stderr | ForEach-Object { Write-Host $_ -ForegroundColor DarkGray }
        }
        if (-not (Test-Path $jsonPath)) {
            throw "provider_dev_token did not write $jsonPath"
        }
        $out = Get-Content -Path $jsonPath -Raw | ConvertFrom-Json
        return $out
    }
    finally {
        Pop-Location
        if ($null -ne $prevDb) { $env:DATABASE_URL = $prevDb } else { Remove-Item env:DATABASE_URL -ErrorAction SilentlyContinue }
        if (Test-Path $jsonPath) { Remove-Item -Path $jsonPath -Force -ErrorAction SilentlyContinue }
    }
}

Load-DotEnv (Join-Path $repoRoot ".env")

$pgUser = if ($env:POSTGRES_USER) { $env:POSTGRES_USER } else { "proxyhubb" }
$pgDb = if ($env:POSTGRES_DB) { $env:POSTGRES_DB } else { "proxyhubb" }
$pgPass = $env:POSTGRES_PASSWORD
$pgPort = if ($PostgresHostPort) { $PostgresHostPort } elseif ($env:POSTGRES_HOST_PORT) { $env:POSTGRES_HOST_PORT } else { "55432" }

if (-not $pgPass) { throw "POSTGRES_PASSWORD not set in .env" }
if (-not $env:TOKEN_HMAC_SECRET) { throw "TOKEN_HMAC_SECRET not set in .env" }

$composeEnvPath = Join-Path $repoRoot "config\docker\provider.compose.env"
$dockerTomlPath = Join-Path $repoRoot "config\docker\provider.toml"

# Host URL for `go run provider_dev_token` (localhost mapped port). Compose uses POSTGRES_* in docker-compose.yml.
$pgPassEncoded = [uri]::EscapeDataString($pgPass)
$hostDatabaseUrl = "postgresql://${pgUser}:${pgPassEncoded}@localhost:${pgPort}/${pgDb}?sslmode=disable"

Write-Host "=== Bootstrap provider (Docker) ===" -ForegroundColor Cyan
Write-Host "API: $ApiBaseUrl  Postgres: localhost:$pgPort" -ForegroundColor DarkGray

$pgContainer = "proxyhubb-postgres-1"
if (-not (Test-PostgresDockerAuth $pgContainer $pgUser $pgDb $pgPass)) {
    Write-Host "[FAIL] POSTGRES_PASSWORD in .env does not match the running Postgres volume." -ForegroundColor Red
    Write-Host "  Fix: set POSTGRES_PASSWORD to the password used when the volume was first created," -ForegroundColor Yellow
    Write-Host "  or reset the DB volume (destructive): docker compose down -v" -ForegroundColor Yellow
    Write-Host "  Also align DATABASE_URL in .env with POSTGRES_USER / POSTGRES_PASSWORD / POSTGRES_DB." -ForegroundColor Yellow
    throw "Postgres auth check failed"
}
Write-Host "[OK] Postgres password matches container" -ForegroundColor Green

try {
    $h = Invoke-RestMethod "$ApiBaseUrl/health" -TimeoutSec 10
    if ($h.status -ne "ok") { throw "API health not ok" }
    Write-Host "[OK] control-api reachable" -ForegroundColor Green
}
catch {
    throw "control-api not reachable at $ApiBaseUrl. Run: docker compose up -d"
}

$existing = Read-ComposeEnv $composeEnvPath
$apiKey = $existing.ApiKey
$signingKey = $existing.SigningKey

if ($ResyncHotkey) {
    if (-not $signingKey) {
        Write-Host "Generating signing key and syncing node hotkey..." -ForegroundColor Cyan
        $out = Invoke-ProviderDevToken @("-signing-only", "-generate-signing-key", "-sync-hotkey") $hostDatabaseUrl
        $signingKey = $out.signing_key
        if (-not $apiKey) { throw "ResyncHotkey requires existing PROXYHUB_API_KEY in $composeEnvPath (run bootstrap first)" }
        Write-ComposeEnv $composeEnvPath $apiKey $signingKey
        Write-Host "[OK] Hotkey resynced on node $($out.hotkey_synced_node_id)" -ForegroundColor Green
    }
    else {
        Write-Host "Resyncing hotkey from existing signing key..." -ForegroundColor Cyan
        $out = Invoke-ProviderDevToken @("-signing-only", "-signing-key", $signingKey, "-sync-hotkey") $hostDatabaseUrl
        Write-Host "[OK] Hotkey resynced on node $($out.hotkey_synced_node_id)" -ForegroundColor Green
    }
}
elseif (-not $ForceNewToken -and (Test-ProviderAuth $ApiBaseUrl $apiKey) -and $signingKey) {
    Write-Host "[OK] Reusing $composeEnvPath (-ForceNewToken to remint)" -ForegroundColor Green
}
elseif (-not $ForceNewToken -and (Test-ProviderAuth $ApiBaseUrl $apiKey) -and -not $signingKey) {
    Write-Host "Adding signing key to existing provider token..." -ForegroundColor Cyan
    $out = Invoke-ProviderDevToken @(
        "-signing-only",
        "-generate-signing-key",
        "-sync-hotkey",
        "-write-toml", $dockerTomlPath
    ) $hostDatabaseUrl
    $signingKey = $out.signing_key
    Write-ComposeEnv $composeEnvPath $apiKey $signingKey
    Write-Host "[OK] Wrote signing key to $composeEnvPath" -ForegroundColor Green
}
else {
    Write-Host "Minting provider token + signing key..." -ForegroundColor Cyan
    $out = Invoke-ProviderDevToken @(
        "-generate-signing-key",
        "-sync-hotkey",
        "-write-toml", $dockerTomlPath
    ) $hostDatabaseUrl
    $apiKey = $out.token
    $signingKey = $out.signing_key
    if (-not $apiKey -or -not $signingKey) {
        throw "provider_dev_token missing token or signing_key"
    }
    Write-ComposeEnv $composeEnvPath $apiKey $signingKey
    Write-Host "[OK] Wrote $composeEnvPath" -ForegroundColor Green
    if ($out.hotkey_synced_node_id) {
        Write-Host "[OK] Synced hotkey on node $($out.hotkey_synced_node_id)" -ForegroundColor Green
    }
}

if (-not $SkipAuthTest) {
    $env:PROXYHUB_API_KEY = $apiKey
    & (Join-Path $PSScriptRoot "test-provider-auth.ps1") -ApiBaseUrl $ApiBaseUrl -ApiKey $apiKey
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
}

Write-Host ""
Write-Host "Start signed provider in Docker (QUIC tunnel):" -ForegroundColor Cyan
Write-Host "  .\scripts\compose-up-dev.ps1"
Write-Host "  # or: docker compose -f docker-compose.yml -f docker-compose.provider.yml --profile provider up -d"
Write-Host ""
Write-Host "Verify proofs (wait ~2 min after start):" -ForegroundColor Cyan
Write-Host "  .\scripts\verify-provider-proofs-docker.ps1"

if ($StartProvider) {
    $composeArgs = @("compose", "-f", "docker-compose.yml", "-f", "docker-compose.provider.yml", "--profile", "provider")
    if ($Build) {
        & docker @composeArgs build provider-node edge-gateway
        if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
    }
    & docker @composeArgs up -d edge-gateway provider-node
    if ($LASTEXITCODE -ne 0) {
        Write-Host "edge-gateway/provider-node failed (often host port 9090/9092 in use). See docs/PROVIDER_PROOFS_DOCKER.md troubleshooting." -ForegroundColor Red
        exit $LASTEXITCODE
    }
    Write-Host "[OK] edge-gateway + provider-node started (PROVIDER_TRANSPORT=quic via provider overlay)" -ForegroundColor Green
    Write-Host "  Gateway health: http://localhost:${env:EDGE_GATEWAY_PORT -replace '^$','8090'}/health"
    Write-Host "  Logs: docker logs -f proxyhubb-provider-node"
}
