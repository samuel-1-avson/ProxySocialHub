#!/usr/bin/env bash
# Full Docker E2E: control-api + edge-gateway + provider-node (provider compose profile).
# Mirrors scripts/quic-provider-e2e-docker.ps1 for Linux CI and bash shells.
#
# Usage (repo root):
#   ./scripts/provider-docker-e2e.sh
#   PROVIDER_E2E_SKIP_HEAL=1 ./scripts/provider-docker-e2e.sh

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

if [[ -f .env ]]; then
  set -a
  # shellcheck disable=SC1091
  source .env
  set +a
fi

COMPOSE_PROVIDER=( -f docker-compose.yml -f docker-compose.provider.yml --profile provider )
TOKEN_JSON="${TMPDIR:-/tmp}/proxyhubb-provider-token-$$.json"
COMPOSE_ENV="config/docker/provider.compose.env"

cleanup() {
  rm -f "$TOKEN_JSON"
}
trap cleanup EXIT

wait_container_healthy() {
  local name=$1
  local deadline=$((SECONDS + 180))
  while true; do
    local status
    status="$(docker inspect -f '{{.State.Health.Status}}' "$name" 2>/dev/null || echo missing)"
    if [[ "$status" == "healthy" ]]; then
      return 0
    fi
    if (( SECONDS > deadline )); then
      echo "Timed out waiting for $name (status=$status)" >&2
      return 1
    fi
    sleep 3
  done
}

if [[ "${PROVIDER_E2E_SKIP_HEAL:-}" != "1" ]] && [[ -x scripts/compose-heal-postgres-password.sh ]]; then
  echo "Ensuring Postgres password matches compose..."
  ./scripts/compose-heal-postgres-password.sh || true
fi

echo "Starting core stack..."
docker compose up -d postgres redis nats db-migrate zk-prover control-api
wait_container_healthy proxyhubb-control-api-1

echo "Minting dev provider credentials..."
mkdir -p config/docker
(
  cd services/control-api
  go run ./cmd/provider_dev_token \
    -ensure-profile \
    -generate-signing-key \
    -api-url http://localhost:18080 \
    -output-json "$TOKEN_JSON"
)

API_KEY="$(python3 -c "import json,sys; print(json.load(open(sys.argv[1]))['token'])" "$TOKEN_JSON")"
SIGN_KEY="$(python3 -c "import json,sys; print(json.load(open(sys.argv[1])).get('signing_key',''))" "$TOKEN_JSON")"

cat >"$COMPOSE_ENV" <<EOF
# Generated by provider-docker-e2e.sh — do not commit
PROXYHUB_API_KEY=${API_KEY}
PROXYHUB_PROVIDER_SIGNING_KEY=${SIGN_KEY}
EOF

echo "Building and starting edge-gateway + provider-node..."
docker compose "${COMPOSE_PROVIDER[@]}" build edge-gateway provider-node
docker compose "${COMPOSE_PROVIDER[@]}" up -d edge-gateway provider-node

echo "Waiting for provider tunnel (up to 90s)..."
ok=0
for _ in $(seq 1 30); do
  sleep 3
  gw_log="$(docker logs proxyhubb-edge-gateway-1 2>&1 || true)"
  pn_log="$(docker logs proxyhubb-provider-node 2>&1 || true)"
  if echo "$pn_log" | grep -q "Handshake complete, tunnel established"; then
    ok=1
    break
  fi
done

echo ""
echo "=== Gateway ==="
docker logs proxyhubb-edge-gateway-1 2>&1 | tail -n 12

echo ""
echo "=== Provider-node ==="
docker logs proxyhubb-provider-node 2>&1 | tail -n 15

if [[ "$ok" != "1" ]]; then
  echo "E2E failed: provider-node did not log tunnel establishment." >&2
  exit 1
fi

METRICS_PORT="${EDGE_GATEWAY_METRICS_PORT:-9092}"
if curl -sf "http://127.0.0.1:${METRICS_PORT}/metrics" | grep -qE 'edge_gateway_healthy_providers\s+[1-9]'; then
  echo "edge_gateway_healthy_providers >= 1"
else
  echo "Warning: could not confirm healthy_providers on :${METRICS_PORT}/metrics" >&2
fi

echo ""
echo "Provider Docker E2E passed (tunnel + healthy providers)."
echo "Run ./scripts/marketplace-buy-connect-e2e.sh with MARKETPLACE_E2E_SKIP_STACK=1 for full buy → activate → CONNECT."
